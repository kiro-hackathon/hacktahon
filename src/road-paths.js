export function getRoadPath(originId, destinationId) {
  if (!originId || !destinationId) return null;
  return roadPaths[`${originId}-${destinationId}`] || null;
}

function distSq(c1, c2) {
  const dLat = c1[0] - c2[0];
  const dLng = c1[1] - c2[1];
  return dLat * dLat + dLng * dLng;
}

/** Finds the nearest road corridor path connecting two locations/coordinates. */
export function findNearestRoadPath(from, to) {
  if (!from || !to) return null;
  const fromCoord = from.coordinates || (Array.isArray(from) ? from : null);
  const toCoord = to.coordinates || (Array.isArray(to) ? to : null);
  if (!fromCoord || !toCoord) return null;

  if (from.id && to.id) {
    const direct = getRoadPath(from.id, to.id);
    if (direct) return direct;
  }

  let nearestFrom = sourcedLandmarks[0];
  let minFromDist = Infinity;
  for (const s of sourcedLandmarks) {
    const d = distSq(fromCoord, s.coordinates);
    if (d < minFromDist) {
      minFromDist = d;
      nearestFrom = s;
    }
  }

  let nearestTo = sourcedLandmarks[0];
  let minToDist = Infinity;
  for (const s of sourcedLandmarks) {
    const d = distSq(toCoord, s.coordinates);
    if (d < minToDist) {
      minToDist = d;
      nearestTo = s;
    }
  }

  if (nearestFrom.id === nearestTo.id) {
    return [fromCoord, nearestFrom.coordinates, toCoord];
  }

  const baseRoad = getRoadPath(nearestFrom.id, nearestTo.id);
  if (!baseRoad) return [fromCoord, toCoord];

  return [fromCoord, ...baseRoad, toCoord];
}
